/* التركيز: ما الذي يُقدَّم له أوّلاً داخل الوحدة، على ما جاء به.

   وكان البرنامج يسأله «لماذا تتعلّم؟» ثمّ يَخزن جوابَه ولا يَقرؤه
   أحدٌ بعدُ — سؤالٌ بلا أثر. وفوقه تعليقٌ يَزعم أنّ «لهذا أثراً في
   ما يُقدَّم له»، وهو زعمٌ لا يُصدّقه سطر.

   فصار له أثرُه ها هنا: محطّاتُ الوحدة واحدةٌ لا تُنقَص — لا يُعفى
   من قراءةٍ ولا كتابة — وإنّما يَتقدّم منها ما جاء لأجله. فصاحبُ
   الشغل يَبدأ بالكتابة والترجمة، وصاحبُ الكلام يَبدأ بالسماع
   والمشهد الحيّ. ثمّ يُتمّ الباقي قبل البوابة.

   وما لا يُنقَص لا يُغشّ به: الوحدةُ تُقفَل حتّى تَتمّ كلُّها.

   ولا تَستورد هذه الوحدةُ شيئاً: هي مرجعُ القيم المقبولة، تَقرؤها
   state.js لتُنقّي الخطّةَ الواردة — فلو استوردت الحالةَ لدارت
   الاستيرادات في حلقة. والخطّةُ تُمرَّر إليها، ولا تُلتقَط. */

/* ولا تُمَسّ المفرداتُ ولا الدروس: من لم يملك الكلمةَ لم تنفعه
   القاعدة، ومن لم يَعرف القاعدةَ لم يَكتب بها. فالمقدَّمُ ما بعدهما. */
const ORDER = {
  work:   {skills: ['write', 'tr', 'read', 'dict'], speakFirst: false,
           t: 'شغلك',             sub: 'تُقدَّم لك الكتابةُ والترجمة'},
  study:  {skills: ['read', 'write', 'tr', 'dict'], speakFirst: false,
           t: 'دراستك',           sub: 'تُقدَّم لك القراءةُ والكتابة'},
  travel: {skills: ['dict', 'read', 'tr', 'write'], speakFirst: true,
           t: 'سفرك',             sub: 'يُقدَّم لك السماعُ والكلام'},
  talk:   {skills: ['dict', 'tr', 'read', 'write'], speakFirst: true,
           t: 'كلامك مع الناس',   sub: 'يُقدَّم لك الكلامُ والسماع'}
};

/* القيمُ المقبولة، ومرجعُها هذا الموضعُ وحدَه.

   وكانت ثلاثةَ مواضعَ تَختلف في الجواب الواحد: setPlan تَقسِر
   المجهولَ إلى talk، وcleanPlan تَقبل أيَّ نصٍّ دون اثنتي عشرة
   حرفاً كما هو، وfocusBy تَردّ null. فجاءت خطّةٌ من ملفٍّ مستورَدٍ
   فيها why:"zzz" فنَجَت من التنقية، ثمّ سَقط أثرُها صامتاً — وهو
   عينُ «سؤالٍ بلا أثر» الذي كُتبت هذه الوحدةُ لرفعه. */
export const FOCUS_KEYS = Object.keys(ORDER);
export const FOCUS_FALLBACK = 'talk';
export const isFocus = w =>
  typeof w === 'string' && Object.prototype.hasOwnProperty.call(ORDER, w);

/* بالاسم — ويُسأل به في شاشة وضع الخطّة قبل أن تُحفَظ.

   وبـhasOwnProperty لا بـ[w] وحده: مفتاحٌ من حالةٍ واردةٍ قد يكون
   "constructor" فيَرجع دالّةً من السلسلة، وهي ليست تركيزاً. */
export const focusBy = w => isFocus(w) ? ORDER[w] : null;

/* تركيزُ خطّةٍ بعينها. وتُمرَّر إليها الخطّةُ ولا تُقرأ من الحالة،
   فتَبقى هذه الوحدةُ بلا استيراد. */
export const focusOf = plan => focusBy((plan || {}).why);

/* ترتيبُ المهارات على تركيزه.

   ولا تُسقَط منها واحدة: ما لم يُذكَر في القائمة يَلحق بآخرها، فلو
   زِيدت مهارةٌ يوماً ولم تُذكَر ها هنا ظهرت ولم تَضِع. وحارسُها
   اختبارٌ يُطابق مفاتيحَ ORDER بمهاراتِ unit-plan، فلا تَغيب واحدةٌ
   في ذيل القائمة أبداً ولا أحدَ يَعلم. */
export function orderSkills(list, f){
  if (!f) return list.slice();
  const rank = k => {
    const i = f.skills.indexOf(k);
    return i < 0 ? f.skills.length : i;
  };
  return list.slice().sort((a, b) => rank(a.k) - rank(b.k));
}
