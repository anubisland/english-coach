export function helpCard(){
  return card('دليل الاستعمال',
    '<p class="muted">أسئلةٌ قد تَعرِض لك، وجوابُها في سطرين.</p>'
    + '<div style="margin-top:4px">'
    + Q.map(x => {
        const open = S.help === x.k;
        return `<div style="border-bottom:1px solid var(--line)">
          <button class="btn ghost" style="width:100%;margin:0;padding:12px 2px;
            text-align:start;justify-content:flex-start;background:transparent;
            font-size:14.5px;font-weight:${open ? '700' : '600'}"
            onclick="openHelp('${x.k}')">${open ? '▾' : '▸'} ${x.q}</button>
          ${open ? `<div class="muted" style="font-size:13.5px;line-height:1.95;
            padding:2px 6px 14px">${x.a}
            ${x.act ? `<div class="row" style="justify-content:flex-start;margin-top:10px">
              <button class="btn" onclick="${x.act[1]}">${x.act[0]}</button></div>` : ''}
            </div>` : ''}
        </div>`;
      }).join('')
    + '</div>');
}
